"""Experiments for the variable-order synthetic path generator.

The original ``synthetic_experiments.ipynb`` remains the fixed second-order
Fig. 2 reproduction.  This script evaluates the same Convex-NMF machinery on
the path-consistent A2/A3 matrices generated by ``VariableOrderGenerator``.

The default workflow is the mixed *oracle-leaf* VOCMN mechanism workflow:

1. generate complete paths;
2. use all synthetic ``matched_context``/``true_order`` labels to stack real leaf
   contexts up to the requested maximum order into one X_j per current node;
3. construct A1/A2/A3 and either population or suffix-regularized target matrices;
4. scan Convex-NMF ranks and aggregate median flow overlap;
5. match learned state-node output distributions to extreme observed contexts;
6. compare the match against a random convex-combination null model;
7. save the three-panel Fig. 2 figure and a long CSV/Parquet table.

Use ``--target-mode raw`` only for the fixed A2/A3 diagnostic.  The generator
and this script currently support maximum order 3; orders 4 and 5 are not
implemented.  The default concentration grid is ``c in {0.5, 1.0, 1.5}``.
This script does not claim automatic order selection from unlabeled paths;
that requires a separate end-to-end experiment.

Example (small smoke experiment):

    python variable_order_experiments.py --n-nodes 12 --n-paths 8 \
        --path-length 120 --repeats 2 --max-rank 6 --n-candidates 2 \
        --conditions mixed --orders 3 --out-dir results/variable_order
"""

