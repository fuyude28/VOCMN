def leaf_context_groups(
    labels: pd.DataFrame,
    path_ids: Sequence[int],
    node_ids: Sequence[Any],
    max_order: int,
) -> Dict[Any, Tuple[np.ndarray, List[Tuple[Any, ...]]]]:
    """Build target matrices from true leaf contexts in selected paths.

    Each column is a context that was actually matched by the generator.  For
    a mixed tree this naturally stacks order-1, order-2 and order-3 leaves for
    the same current node, subject to ``max_order``.
    """
    if max_order not in (1, 2, 3):
        raise ValueError("max_order must be 1, 2, or 3")
    node_ids = list(node_ids)
    node_to_row = {node_id: index for index, node_id in enumerate(node_ids)}
    selected = labels[
        labels["path_id"].isin(set(path_ids))
        & (labels["true_order"] <= max_order)
    ]
    groups: Dict[Any, Tuple[np.ndarray, List[Tuple[Any, ...]]]] = {}
    for current in node_ids:
        subset = selected[
            selected["matched_context"].map(lambda context: context[-1] == current)
        ]
        contexts = sorted(
            set(subset["matched_context"].tolist()),
            key=lambda context: (len(context), str(context)),
        )
        if not contexts:
            continue
        context_to_column = {context: index for index, context in enumerate(contexts)}
        matrix = np.zeros((len(node_ids), len(contexts)), dtype=float)
        for row in subset.itertuples(index=False):
            context = row.matched_context
            matrix[node_to_row[row.next_node], context_to_column[context]] += 1.0
        groups[current] = (matrix, contexts)
    return groups


def context_matrix_by_current_node(
    count_matrix,
    node_ids: Sequence[Any],
) -> Dict[Any, Tuple[np.ndarray, List[Tuple[Any, ...]]]]:
    """Group an A2/A3 count matrix into A_j matrices by context suffix."""
    node_ids = list(node_ids)
    groups: Dict[Any, Tuple[np.ndarray, List[Tuple[Any, ...]]]] = {}
    for current in node_ids:
        columns = [
            column
            for column, context in enumerate(count_matrix.contexts)
            if context[-1] == current
        ]
        if not columns:
            continue
        contexts = [count_matrix.contexts[column] for column in columns]
        groups[current] = (count_matrix.matrix[:, columns], contexts)
    return groups


def make_physical_nodes(
    count_matrix,
    node_ids: Sequence[Any],
) -> Dict[Any, PhysicalNode]:
    """Construct raw fixed-order nodes using the legacy global M1 prior."""
    groups = context_matrix_by_current_node(count_matrix, node_ids)
    nodes: Dict[Any, PhysicalNode] = {}
    for current, (matrix, contexts) in groups.items():
        node = PhysicalNode.from_adjacency_matrix(
            A=matrix,
            id=current,
            arr_preds=np.asarray(contexts, dtype=object),
            arr_succs=np.asarray(list(node_ids), dtype=object),
        )
        node.create_adjusted_transition_matrix()
        nodes[current] = node
    return nodes


def _normalized_columns(counts: np.ndarray) -> np.ndarray:
    """Normalize count columns, returning zeros for columns with no support."""
    totals = counts.sum(axis=0)
    result = np.zeros_like(counts, dtype=float)
    supported = totals > 0.0
    result[:, supported] = counts[:, supported] / totals[supported]
    return result


def _estimate_suffix_mu(A: np.ndarray, B: np.ndarray) -> float:
    """Estimate one leave-one-out pseudocount strength for a context order."""
    if A.size == 0:
        return 1.0
    totals = A.sum(axis=0)

    def objective(params):
        mu = float(params[0])
        denominator = np.maximum(totals - 1.0 + mu, 1e-16)
        numerator = np.maximum(A - 1.0 + mu * B, 1e-16)
        return float(-(A * np.log(numerator / denominator)).sum())

    fitted = minimize(
        objective,
        x0=[1.0],
        bounds=[(1e-12, np.inf)],
        method="L-BFGS-B",
    )
    return float(fitted.x[0]) if fitted.success else 1.0


def make_suffix_regularized_leaf_nodes(
    labels: pd.DataFrame,
    path_ids: Sequence[int],
    paths: Sequence[Sequence[Any]],
    node_ids: Sequence[Any],
    max_order: int,
) -> Tuple[
    Dict[Any, PhysicalNode],
    Dict[Any, List[Tuple[Any, ...]]],
    Dict[int, float],
]:
    """Build oracle-leaf X_j with suffix-specific parent posteriors.

    For a leaf context h, its prior B_h is the empirical posterior of the
    suffix parent: order-1 leaves use the first-order posterior, order-2
    leaves use the order-1 parent, and order-3 leaves use the order-2 parent.
    The resulting columns are X_h=(A_h+mu_l B_h)/(n_h+mu_l), with one
    leave-one-out pseudocount strength per context order.
    """
    groups = leaf_context_groups(labels, path_ids, node_ids, max_order)
    node_ids = list(node_ids)
    raw_by_order = {
        order: count_matrix_from_paths(paths, node_ids, order)
        for order in range(1, max_order + 1)
    }
    raw_posteriors: Dict[int, Dict[Tuple[Any, ...], np.ndarray]] = {}
    for order, count_matrix in raw_by_order.items():
        raw_posteriors[order] = {
            context: column
            for context, column in zip(
                count_matrix.contexts,
                _normalized_columns(count_matrix.matrix).T,
            )
        }

    matrices_by_order: Dict[int, List[np.ndarray]] = {order: [] for order in range(1, max_order + 1)}
    priors_by_order: Dict[int, List[np.ndarray]] = {order: [] for order in range(1, max_order + 1)}
    raw_groups: Dict[Any, Tuple[np.ndarray, List[Tuple[Any, ...]]]] = {}
    for current, (A, contexts) in groups.items():
        B = np.zeros_like(A, dtype=float)
        for column, context in enumerate(contexts):
            context_order = len(context)
            prior_order = 2 if context_order == 3 else 1
            parent = context[1:] if context_order == 3 else (context[-1],)
            prior = raw_posteriors[prior_order].get(parent)
            if prior is None:
                raise ValueError(f"missing suffix posterior for context {context}")
            B[:, column] = prior
            matrices_by_order[context_order].append(A[:, column : column + 1])
            priors_by_order[context_order].append(B[:, column : column + 1])
        raw_groups[current] = (A, contexts)

    mu_by_order = {
        order: _estimate_suffix_mu(
            np.hstack(matrices_by_order[order])
            if matrices_by_order[order]
            else np.empty((len(node_ids), 0)),
            np.hstack(priors_by_order[order])
            if priors_by_order[order]
            else np.empty((len(node_ids), 0)),
        )
        for order in range(1, max_order + 1)
    }

    nodes: Dict[Any, PhysicalNode] = {}
    contexts_by_node: Dict[Any, List[Tuple[Any, ...]]] = {}
    for current, (A, contexts) in raw_groups.items():
        B = np.zeros_like(A, dtype=float)
        for column, context in enumerate(contexts):
            prior_order = 2 if len(context) == 3 else 1
            parent = context[1:] if len(context) == 3 else (context[-1],)
            B[:, column] = raw_posteriors[prior_order][parent]
        X = np.zeros_like(A, dtype=float)
        for column, context in enumerate(contexts):
            mu = mu_by_order[len(context)]
            total = A[:, column].sum()
            X[:, column] = (A[:, column] + mu * B[:, column]) / (total + mu)
        node = PhysicalNode.from_adjacency_matrix(
            A=A,
            id=current,
            arr_preds=np.asarray(contexts, dtype=object),
            arr_succs=np.asarray(node_ids, dtype=object),
        )
        node.X = X
        node.mu_by_order = mu_by_order
        nodes[current] = node
        contexts_by_node[current] = contexts
    return nodes, contexts_by_node, mu_by_order


def make_population_leaf_nodes(
    labels: pd.DataFrame,
    path_ids: Sequence[int],
    data,
    max_order: int,
) -> Tuple[
    Dict[Any, PhysicalNode],
    Dict[Any, List[Tuple[Any, ...]]],
    Dict[int, float],
]:
    """Build leaf target matrices from the generator's population probabilities.

    The observed leaf contexts still determine the columns and their flow
    weights, but each target column is the true ``P*(successor | context)``.
    This isolates the shared-mode mechanism from finite path sampling noise.
    ``matched_context`` is used only to define the oracle-leaf mechanism target;
    no generated count is used to estimate these probabilities.
    """
    groups = leaf_context_groups(labels, path_ids, data.node_ids, max_order)
    nodes: Dict[Any, PhysicalNode] = {}
    contexts_by_node: Dict[Any, List[Tuple[Any, ...]]] = {}
    for current, (A, contexts) in groups.items():
        probabilities = []
        for context in contexts:
            spec = data.context_specs.resolve(context)
            if spec is None or not spec.is_leaf:
                raise ValueError(f"missing true leaf population context {context}")
            probabilities.append(np.asarray(spec.probabilities, dtype=float))
        X = np.column_stack(probabilities)
        node = PhysicalNode.from_adjacency_matrix(
            A=A,
            id=current,
            arr_preds=np.asarray(contexts, dtype=object),
            arr_succs=np.asarray(data.node_ids, dtype=object),
        )
        node.X = X
        node.target_source = "population"
        nodes[current] = node
        contexts_by_node[current] = contexts
    return nodes, contexts_by_node, {}


def process_nodes(
    nodes: Dict[Any, PhysicalNode],
    max_rank: int,
    n_candidates: int,
    initialise: str = "kmeans",
) -> None:
    """Run the existing Convex-NMF rank scan on every current node."""
    for node in nodes.values():
        # K-means needs at least as many context columns as clusters.
        rank_limit = min(max_rank, node.n_preds)
        if rank_limit < 1:
            continue
        node.process(
            max_rank=rank_limit,
            n_candidates=n_candidates,
            overlap_threshold=None,
            initialise=initialise,
        )


def train_target_flow_overlap(
    nodes: Dict[Any, PhysicalNode],
    rank: int,
) -> float:
    """Aggregate reconstruction overlap on the training target matrices."""
    numerator = 0.0
    denominator = 0.0
    for node in nodes.values():
        if rank not in node.dict_flow_overlap:
            continue
        total_flow = float(node.A.sum())
        numerator += total_flow * float(node.dict_flow_overlap[rank])
        denominator += total_flow
    return numerator / denominator if denominator else np.nan


def node_flow_overlap(
    nodes: Dict[Any, PhysicalNode],
    rank: int,
) -> Dict[Any, float]:
    """Return per-current-node flow overlap for the requested rank."""
    return {
        current: float(node.dict_flow_overlap[rank])
        for current, node in nodes.items()
        if rank in node.dict_flow_overlap
    }


def median_node_flow_overlap(
    nodes: Dict[Any, PhysicalNode],
    rank: int,
) -> float:
    """Match the original Fig. 2 statistic: median across current nodes."""
    values = list(node_flow_overlap(nodes, rank).values())
    return float(np.median(values)) if values else np.nan


# Backward-compatible name for callers of the earlier diagnostic script.
global_flow_overlap = train_target_flow_overlap


def _best_assignment_similarity(
    planted_modes: np.ndarray,
    learned_states: np.ndarray,
) -> float:
    """Match columns by maximum flow overlap and return the mean overlap."""
    if learned_states.shape[1] != planted_modes.shape[1]:
        raise ValueError("planted and learned state counts must match")
    overlap = np.zeros((planted_modes.shape[1], learned_states.shape[1]))
    for mode in range(planted_modes.shape[1]):
        for state in range(learned_states.shape[1]):
            overlap[mode, state] = np.minimum(
                planted_modes[:, mode], learned_states[:, state]
            ).sum()
    rows, columns = linear_sum_assignment(overlap, maximize=True)
    return float(overlap[rows, columns].mean())


def _sample_null_states(
    X: np.ndarray,
    n_states: int,
    rng: np.random.Generator,
) -> np.ndarray:
    """Create random convex combinations of observed context columns."""
    ratios = rng.dirichlet(np.ones(X.shape[1]), size=n_states)
    return X @ ratios.T


def _extreme_observed_contexts(
    target: np.ndarray,
    planted_modes: np.ndarray,
) -> np.ndarray:
    """Select the observed target columns closest to each planted mode.

    This matches the reference construction used by the original Fig. 2C:
    learned and null states are both compared with the same observed extreme
    context distributions rather than directly with the planted modes.
    """
    if target.shape[1] < planted_modes.shape[1]:
        raise ValueError("not enough target contexts for mode matching")
    selected = []
    for mode_index in range(planted_modes.shape[1]):
        overlaps = [
            float(np.minimum(planted_modes[:, mode_index], target[:, column]).sum())
            for column in range(target.shape[1])
        ]
        selected.append(target[:, int(np.argmax(overlaps))])
    return np.column_stack(selected)


def mode_matching(
    nodes: Dict[Any, PhysicalNode],
    modes_by_node: Dict[Any, np.ndarray],
    n_modes: int,
    rng: np.random.Generator,
    n_null: int = 50,
) -> Tuple[Dict[Any, float], Dict[Any, List[float]]]:
    """Return learned and null mode similarities by current node."""
    learned: Dict[Any, float] = {}
    null: Dict[Any, List[float]] = {}
    for current, node in nodes.items():
        if n_modes not in node.dict_solutions:
            continue
        # A first-order target has only one root column per current node, so
        # there are not enough observed contexts for an n_modes-way matching.
        if node.n_preds < n_modes:
            continue
        learned_states = node.dict_solutions[n_modes].Xhat_out
        planted = modes_by_node[current]
        reference_states = _extreme_observed_contexts(node.X, planted)
        learned[current] = _best_assignment_similarity(reference_states, learned_states)
        null[current] = []
        for _ in range(n_null):
            random_states = _sample_null_states(node.X, n_modes, rng)
            null[current].append(
                _best_assignment_similarity(reference_states, random_states)
            )
    return learned, null


def run_single_replicate(
    *,
    n_nodes: int,
    n_modes: int,
    n_paths: int,
    path_length: int,
    condition: str,
    order: int,
    overlap_fraction: float,
    dirichlet_concentration: float,
    rho2: float,
    rho3: float,
    max_rank: int,
    n_candidates: int,
    target_mode: str,
    target_source: str,
    anchor_contexts: bool,
    generator_seed: int,
    null_seed: int,
    n_null: int,
) -> Dict[str, Any]:
    """Generate one replicate and run the full-data mechanism pipeline."""
    started = time.perf_counter()
    if target_mode not in {"leaf", "raw"}:
        raise ValueError("target_mode must be 'leaf' or 'raw'")
    if target_source not in {"population", "empirical"}:
        raise ValueError("target_source must be 'population' or 'empirical'")
    if target_mode == "raw" and target_source != "empirical":
        raise ValueError("raw targets only support target_source='empirical'")
    data = generate_variable_order_data(
        n_nodes=n_nodes,
        n_modes=n_modes,
        n_paths=n_paths,
        path_length=path_length,
        dirichlet_concentration=dirichlet_concentration,
        rho2=rho2,
        rho3=rho3,
        condition=condition,
        q3=0.5,
        overlap_fraction=overlap_fraction,
        anchor_contexts=anchor_contexts,
        seed=generator_seed,
    )
    model_name = "VOCMN" if target_mode == "leaf" else (
        "CMN" if order == 2 else f"CMN-raw-order{order}"
    )
    path_ids = np.arange(len(data.paths))
    all_paths = data.paths
    if target_mode == "leaf":
        if target_source == "population":
            nodes, contexts_by_node, mu_by_order = make_population_leaf_nodes(
                data.transition_labels, path_ids, data, max_order=order
            )
        else:
            groups = leaf_context_groups(
                data.transition_labels, path_ids, data.node_ids, max_order=order
            )
            nodes, contexts_by_node, mu_by_order = make_suffix_regularized_leaf_nodes(
                data.transition_labels,
                path_ids,
                all_paths,
                data.node_ids,
                max_order=order,
            )
        groups = {
            current: (node.A, contexts_by_node[current])
            for current, node in nodes.items()
        }
        counts = None
    else:
        counts = count_matrix_from_paths(all_paths, data.node_ids, order)
        groups = context_matrix_by_current_node(counts, data.node_ids)
        nodes = make_physical_nodes(counts, data.node_ids)
        contexts_by_node = {
            current: contexts for current, (_, contexts) in groups.items()
        }
        mu_by_order = {}
    process_nodes(nodes, max_rank=max_rank, n_candidates=n_candidates)

    anchor_coverage = {}
    if anchor_contexts and condition in {"second", "mixed"}:
        anchor_contexts_by_node = {
            current: {(predecessor, current) for predecessor in data.node_ids[:n_modes]}
            for current in data.node_ids
        }
        for current, expected in anchor_contexts_by_node.items():
            observed = set(contexts_by_node.get(current, []))
            anchor_coverage[current] = len(expected & observed) / len(expected)

    null_rng = np.random.default_rng(null_seed)
    learned, null = mode_matching(
        nodes,
        data.modes,
        n_modes=n_modes,
        rng=null_rng,
        n_null=n_null,
    )
    flow = {
        rank: median_node_flow_overlap(nodes, rank)
        for rank in range(1, max_rank + 1)
    }
    flow_weighted = {
        rank: train_target_flow_overlap(nodes, rank)
        for rank in range(1, max_rank + 1)
    }
    return {
        "condition": condition,
        "order": order,
        "overlap_fraction": overlap_fraction,
        "target_mode": target_mode,
        "target_source": target_source,
        "anchor_contexts": anchor_contexts,
        "anchor_coverage": anchor_coverage,
        "model": model_name,
        "n_modes": n_modes,
        "dirichlet_concentration": dirichlet_concentration,
        "rho2": rho2,
        "rho3": rho3,
        "n_paths": n_paths,
        "path_length": path_length,
        "data": data,
        "paths": all_paths,
        "counts": counts,
        "groups": groups,
        "contexts_by_node": contexts_by_node,
        "mu_by_order": mu_by_order,
        "nodes": nodes,
        "flow_overlap": flow,
        "flow_overlap_weighted": flow_weighted,
        "learned_similarity_by_node": learned,
        "null_similarity_by_node": null,
        "runtime": time.perf_counter() - started,
        "seed": generator_seed,
    }


def run_grid(
    *,
    conditions: Sequence[str],
    orders: Sequence[int],
    modes: Sequence[int],
    concentrations: Sequence[float],
    overlaps: Sequence[float],
    repeats: int,
    seed: int,
    target_mode: str = "leaf",
    target_source: str = "population",
    anchor_contexts: bool = True,
    **kwargs,
) -> List[Dict[str, Any]]:
    """Run a condition/order/mode/concentration/overlap experiment grid."""
    results: List[Dict[str, Any]] = []
    seed_sequence = np.random.SeedSequence(seed)
    model_specs = [(target_mode, order) for order in orders]
    child_sequences = seed_sequence.spawn(
        len(conditions)
        * len(model_specs)
        * len(modes)
        * len(concentrations)
        * len(overlaps)
        * repeats
    )
    child_index = 0
    for condition in conditions:
        for model_mode, order in model_specs:
            if order not in (2, 3):
                raise ValueError("this script currently supports only order 2 and 3")
            for n_modes in modes:
                for concentration in concentrations:
                    for overlap in overlaps:
                        for _ in range(repeats):
                            child = child_sequences[child_index]
                            child_index += 1
                            seeds = child.generate_state(2)
                            results.append(
                                run_single_replicate(
                                    condition=condition,
                                    order=order,
                                    n_modes=n_modes,
                                    dirichlet_concentration=concentration,
                                    overlap_fraction=overlap,
                                    target_mode=model_mode,
                                    target_source=target_source,
                                    anchor_contexts=anchor_contexts,
                                    generator_seed=int(seeds[0]),
                                    null_seed=int(seeds[1]),
                                    **kwargs,
                                )
                            )
    return results


def _group_results(results: Sequence[Dict[str, Any]]):
    groups: Dict[Tuple[str, str, int, int, float, float], List[Dict[str, Any]]] = {}
    for result in results:
        key = (
            result["model"],
            result["condition"],
            result["order"],
            result["n_modes"],
            result["dirichlet_concentration"],
            result["overlap_fraction"],
        )
        groups.setdefault(key, []).append(result)
    return groups


def _draw_target_panel(ax, representative: Dict[str, Any]) -> None:
    """Draw Panel A without rendering unreadable tuple-valued tick labels."""
    representative_node = max(
        representative["nodes"],
        key=lambda current: representative["nodes"][current].A.sum(),
    )
    node = representative["nodes"][representative_node]
    contexts = representative["contexts_by_node"][representative_node]
    image = ax.imshow(
        node.X,
        aspect="auto",
        interpolation="nearest",
        cmap="Blues",
        # Expand the low-to-intermediate probability range while keeping a
        # fixed, comparable scale across representative conditions.
        norm=PowerNorm(gamma=0.45, vmin=0.0, vmax=0.5),
    )
    colorbar = ax.figure.colorbar(
        image,
        ax=ax,
        orientation="horizontal",
        fraction=0.05,
        pad=0.25,
    )
    colorbar.ax.tick_params(labelsize=7, length=2)
    colorbar.set_label("Probability", fontsize=7)
    ax.set_xlabel("Predecessors", fontsize=8)
    ax.set_ylabel("Successors")
    ax.set_xticks([])
    ax.set_yticks([])
    ax.tick_params(axis="y", which="both", left=False, labelleft=False)
    orders = np.asarray([len(context) for context in contexts])
    boundaries = np.where(orders[1:] != orders[:-1])[0] + 0.5
    for boundary in boundaries:
        ax.axvline(boundary, color="white", linewidth=1.5)
    bracket_y = -0.12
    for order in sorted(set(orders.tolist())):
        columns = np.where(orders == order)[0]
        start = float(columns.min()) - 0.5
        end = float(columns.max()) + 0.5
        ax.plot(
            [start, end],
            [bracket_y, bracket_y],
            transform=ax.get_xaxis_transform(),
            color="#444444",
            linewidth=0.8,
            clip_on=False,
        )
        ax.plot(
            [start, start],
            [bracket_y, bracket_y + 0.025],
            transform=ax.get_xaxis_transform(),
            color="#444444",
            linewidth=0.8,
            clip_on=False,
        )
        ax.plot(
            [end, end],
            [bracket_y, bracket_y + 0.025],
            transform=ax.get_xaxis_transform(),
            color="#444444",
            linewidth=0.8,
            clip_on=False,
        )
        if order == 1:
            ax.annotate(
                f"order {order}",
                xy=(float(columns.mean()), bracket_y + 0.005),
                xycoords=ax.get_xaxis_transform(),
                xytext=(end, -0.255),
                textcoords=ax.get_xaxis_transform(),
                ha="right",
                va="top",
                fontsize=7,
                arrowprops={
                    "arrowstyle": "-|>",
                    "color": "#444444",
                    "linewidth": 0.7,
                    "mutation_scale": 6,
                    "shrinkA": 3,
                    "shrinkB": 1,
                },
                annotation_clip=False,
            )
            continue
        label_x = end if len(columns) < 4 else columns.mean()
        label_alignment = "right" if len(columns) < 4 else "center"
        label_y = -0.225 if len(columns) < 4 else -0.17
        ax.text(
            label_x,
            label_y,
            f"order {order}",
            transform=ax.get_xaxis_transform(),
            ha=label_alignment,
            va="top",
            fontsize=7,
        )


def _plot_train_curves(
    ax,
    results: Sequence[Dict[str, Any]],
    concentrations: Optional[Sequence[float]] = None,
    include_legend: bool = True,
) -> None:
    groups = _group_results(results)
    for key, group in groups.items():
        model, condition, order, n_modes, concentration, overlap = key
        if concentrations is not None and concentration not in concentrations:
            continue
        ranks = sorted({rank for result in group for rank in result["flow_overlap"]})
        # Match the original Fig. 2 statistic: pool every current-node
        # overlap across replicates, then take one median per rank.
        medians = []
        for rank in ranks:
            values = [
                value
                for result in group
                for value in node_flow_overlap(result["nodes"], rank).values()
            ]
            medians.append(float(np.nanmedian(values)) if values else np.nan)
        ax.plot(
            ranks,
            medians,
            marker="o",
            linestyle="-",
            label=f"{model}, m={n_modes}, c={concentration:g}",
        )
    ax.set_xlabel("number of state nodes / rank")
    ax.set_ylabel("median flow overlap")
    ax.spines[["top", "right"]].set_visible(False)
    if include_legend:
        ax.legend(frameon=False, fontsize=8)


def plot_formal_main(
    results: Sequence[Dict[str, Any]],
    output_path: Optional[str] = None,
) -> plt.Figure:
    """Plot the manuscript-facing three-panel figure.

    The synthetic mechanism figure is VOCMN-only. Panel B contains the
    training-target overlap of VOCMN across control conditions. The mechanism
    experiment uses all generated paths; CMN comparison belongs to the separate
    end-to-end runner.
    """
    formal_results = [result for result in results if result["model"] == "VOCMN"]
    if not formal_results:
        raise ValueError("formal Fig. 2 requires at least one VOCMN result")
    groups = _group_results(formal_results)
    representative_pool = [
        result for result in formal_results
        if result.get("contexts_by_node")
    ] or formal_results
    representative = max(
        representative_pool,
        key=lambda result: max(
            (node.A.sum() for node in result["nodes"].values()), default=0.0
        ),
    )
    no_anchor_figure = not bool(
        getattr(representative.get("data"), "anchor_contexts", False)
    )
    # Match the compact reference composition: A/B on top, C spanning the
    # bottom row.  The previous 1x3 layout made Panel C labels unreadable.
    plt.rcParams.update(
        {
            "font.family": "sans-serif",
            "font.size": 8,
            "axes.linewidth": 0.8,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "legend.frameon": False,
        }
    )
    fig = plt.figure(figsize=(8.2, 6.6), layout=None)
    grid = fig.add_gridspec(
        2,
        2,
        width_ratios=[0.95, 1.25],
        height_ratios=[1.0, 0.92],
        hspace=0.22,
    )
    ax_a = fig.add_subplot(grid[0, 0])
    ax_b = fig.add_subplot(grid[0, 1])
    ax_c = fig.add_subplot(grid[1, :])
    fig.subplots_adjust(left=0.07, right=0.98, bottom=0.24, top=0.95, wspace=0.20, hspace=0.12)
    _draw_target_panel(ax_a, representative)
    ax_a.text(
        -0.11,
        1.03,
        "A",
        transform=ax_a.transAxes,
        ha="left",
        va="bottom",
        fontweight="bold",
        fontsize=9,
        clip_on=False,
    )
    ax_b.set_title("B", loc="left", fontweight="bold", fontsize=9, pad=8)

    # Panel B: colour identifies the number of planted modes and line style
    # identifies Dirichlet concentration. The least-separated c=1.5 curves
    # are moved into a compact inset so the main panel remains readable.
    palette = {2: "#1F77B4", 5: "#D98200", 10: "#2A9D67"}
    styles = {0.5: "-", 1.0: "--", 1.5: ":"}
    def _plot_b_group(axis, key, group, *, show_knee: bool = True) -> None:
        _, _, _, n_modes, concentration, _ = key
        ranks = sorted({rank for result in group for rank in result["flow_overlap"]})
        medians, lows, highs = [], [], []
        for rank in ranks:
            # Preserve the original statistic (median over current nodes),
            # then quantify replicate-to-replicate variation with a percentile band.
            replicate_values = [
                list(node_flow_overlap(result["nodes"], rank).values())
                for result in group
            ]
            replicate_medians = [
                float(np.nanmedian(values)) for values in replicate_values if values
            ]
            medians.append(float(np.nanmedian(replicate_medians)) if replicate_medians else np.nan)
            if replicate_medians:
                low, high = np.nanpercentile(replicate_medians, [2.5, 97.5])
            else:
                low = high = np.nan
            lows.append(float(low))
            highs.append(float(high))
        color = palette.get(n_modes, "#555555")
        axis.fill_between(
            ranks,
            lows,
            highs,
            color=color,
            alpha=0.12,
            linewidth=0,
            zorder=1,
        )
        axis.plot(
            ranks,
            medians,
            color=color,
            linestyle=styles.get(concentration, "-"),
            marker="o",
            markersize=3,
            linewidth=1.2,
        )
        knee_rank = n_modes
        if show_knee and knee_rank in ranks:
            knee_index = ranks.index(knee_rank)
            axis.plot(
                [knee_rank],
                [medians[knee_index]],
                marker="s",
                markersize=7,
                markerfacecolor="none",
                markeredgecolor="black",
                markeredgewidth=0.9,
                linestyle="none",
                zorder=5,
            )
    for key, group in sorted(groups.items(), key=lambda item: (item[0][3], item[0][4])):
        if key[4] != 1.5:
            _plot_b_group(ax_b, key, group)
    ax_b.set_xlabel("Number of state nodes")
    ax_b.set_ylabel("Median flow overlap")
    ax_b.set_xlim(0.7, 15.3)
    ax_b.set_ylim(0.3, 1.02)
    ax_b.spines[["top", "right"]].set_visible(False)
    mode_handles = [
        plt.Line2D([], [], color=palette[m], marker="o", linewidth=1.2, label=f"{m}")
        for m in sorted(palette)
    ]
    c_handles = [
        plt.Line2D([], [], color="black", linestyle=styles[c], linewidth=1.2, label=f"{c:g}")
        for c in (0.5, 1.0)
    ]
    leg1 = ax_b.legend(
        handles=mode_handles,
        title=r"$n_m$",
        loc="lower left",
        bbox_to_anchor=(0.72, 0.20),
        frameon=False,
        fontsize=7,
        title_fontsize=7,
    )
    ax_b.add_artist(leg1)
    ax_b.legend(
        handles=c_handles,
        title=r"$\eta$",
        loc="lower left",
        bbox_to_anchor=(0.87, 0.20),
        frameon=False,
        fontsize=7,
        title_fontsize=7,
    )
    inset_bounds = [0.20, 0.10, 0.50, 0.35]
    inset = ax_b.inset_axes(inset_bounds, zorder=10)
    inset.set_facecolor("white")
    for key, group in sorted(groups.items(), key=lambda item: item[0][3]):
        if key[4] == 1.5:
            _plot_b_group(inset, key, group, show_knee=True)
    inset.set_title(r"$\eta=1.5$", fontsize=7, pad=2)
    inset.set_xlim(0.7, 15.3)
    inset.set_ylim(0.3, 1.02)
    inset.set_xticks([1, 5, 10, 15])
    inset.set_yticks([0.4, 0.7, 1.0])
    inset.tick_params(labelsize=6, length=2, width=0.6)
    inset.spines["top"].set_visible(True)
    inset.spines["right"].set_visible(True)
    inset.spines["left"].set_linewidth(0.6)
    inset.spines["bottom"].set_linewidth(0.6)

    # Panel C: three mode-count blocks, with one learned/null pair per c.
    mode_values = sorted({key[3] for key in groups})
    concentration_values = sorted({key[4] for key in groups})
    positions = []
    labels = []
    block_centres = []
    block_bounds = []
    cursor = 1.0
    width = 0.28
    gap = 0.35
    for n_modes in mode_values:
        block_start = cursor
        for concentration in concentration_values:
            key = next(
                key for key in groups
                if key[3] == n_modes and key[4] == concentration
            )
            group = groups[key]
            learned = [
                value
                for result in group
                for value in result["learned_similarity_by_node"].values()
            ]
            null = [
                value
                for result in group
                for values in result["null_similarity_by_node"].values()
                for value in values
            ]
            if not learned or not null:
                cursor += 1.0
                continue
            pair_left = cursor
            boxplot = ax_c.boxplot(
                [learned, null],
                positions=[pair_left, pair_left + width],
                widths=0.22,
                patch_artist=True,
                medianprops={"color": "black", "linewidth": 0.8},
                whiskerprops={"linewidth": 0.8},
                capprops={"linewidth": 0.8},
                flierprops={"markersize": 2},
            )
            boxplot["boxes"][0].set_facecolor(palette.get(n_modes, "#777777"))
            boxplot["boxes"][0].set_alpha(0.55)
            boxplot["boxes"][1].set_facecolor("white")
            boxplot["boxes"][1].set_edgecolor(palette.get(n_modes, "#777777"))
            boxplot["boxes"][1].set_hatch("///")
            positions.append(pair_left + width / 2)
            labels.append(f"{concentration:g}")
            cursor += 1.0
        block_end = cursor - 0.65
        block_centres.append((block_start + block_end) / 2)
        block_left = block_start - 0.35
        block_right = block_end + 0.35
        block_bounds.append((block_left, block_right))
        cursor += gap
    ax_c.set_title("C", loc="left", fontweight="bold", fontsize=9, pad=5)
    ax_c.set_ylabel("flow overlap similarity")
    ax_c.set_xlabel(r"$\eta$", labelpad=8)
    ax_c.xaxis.set_label_coords(0.5, -0.09)
    ax_c.set_ylim(0.1, 1.02)
    ax_c.set_xticks(positions, labels, fontsize=7)
    ax_c.spines[["top", "right"]].set_visible(False)
    if not no_anchor_figure:
        ax_c.axhspan(0.1, 0.6, facecolor="#F7F7F7", edgecolor="none", zorder=-2)
        ax_c.text(
            0.985,
            0.81,
            "Our method",
            transform=ax_c.get_yaxis_transform(),
            ha="right",
            va="center",
            fontsize=7,
            color="black",
        )
        ax_c.text(
            0.985,
            0.35,
            "Null model",
            transform=ax_c.get_yaxis_transform(),
            ha="right",
            va="center",
            fontsize=7,
            color="black",
        )
    # Match the compact reference axis: concentration ticks, then the c label,
    # followed by a bracket and its mode-count label for each block.
    bracket_y = -0.16
    for (block_left, block_right), centre, n_modes in zip(
        block_bounds, block_centres, mode_values
    ):
        ax_c.plot(
            [block_left, block_right],
            [bracket_y, bracket_y],
            transform=ax_c.get_xaxis_transform(),
            color="#444444",
            linewidth=0.8,
            clip_on=False,
        )
        ax_c.plot(
            [block_left, block_left],
            [bracket_y, bracket_y + 0.02],
            transform=ax_c.get_xaxis_transform(),
            color="#444444",
            linewidth=0.8,
            clip_on=False,
        )
        ax_c.plot(
            [block_right, block_right],
            [bracket_y, bracket_y + 0.02],
            transform=ax_c.get_xaxis_transform(),
            color="#444444",
            linewidth=0.8,
            clip_on=False,
        )
        ax_c.text(
            centre,
            -0.23,
            f"{n_modes} modes",
            transform=ax_c.get_xaxis_transform(),
            ha="center",
            va="top",
            fontsize=8,
        )
    if no_anchor_figure:
        ax_c.legend(
            handles=[
                plt.Rectangle((0, 0), 1, 1, facecolor="#777777", alpha=0.55, label="Our method"),
                plt.Rectangle((0, 0), 1, 1, facecolor="white", edgecolor="#777777", hatch="///", label="Null model"),
            ],
            frameon=False,
            fontsize=7,
            loc="lower right",
            bbox_to_anchor=(0.98, 0.12),
        )
    if output_path:
        fig.savefig(output_path, dpi=200)
    return fig


def results_long_table(results: Sequence[Dict[str, Any]]) -> pd.DataFrame:
    """Flatten replicate/node/rank results into an analysis-ready long table."""
    rows: List[Dict[str, Any]] = []
    for result in results:
        learned_by_node = result["learned_similarity_by_node"]
        null_by_node = result["null_similarity_by_node"]
        for current, node in result["nodes"].items():
            learned = learned_by_node.get(current, np.nan)
            null_values = null_by_node.get(current, [])
            null = float(np.mean(null_values)) if null_values else np.nan
            for rank, flow in node.dict_flow_overlap.items():
                rows.append(
                    {
                        "condition": result["condition"],
                        "model": result["model"],
                        "target_mode": result["target_mode"],
                        "target_source": result["target_source"],
                        "anchor_contexts": result["anchor_contexts"],
                        "anchor_coverage": result["anchor_coverage"].get(
                            current, np.nan
                        ),
                        "order": result["order"],
                        "current_node": current,
                        "rank": rank,
                        "flow_overlap": float(flow),
                        "flow_overlap_weighted": result["flow_overlap_weighted"].get(
                            rank, np.nan
                        ),
                        "mode_similarity": learned
                        if rank == result["n_modes"]
                        else np.nan,
                        "null_similarity": null
                        if rank == result["n_modes"]
                        else np.nan,
                        "seed": result["seed"],
                        "context_count": node.n_preds,
                        "flow": float(node.A.sum()),
                        "runtime": result["runtime"],
                        "n_modes": result["n_modes"],
                        "dirichlet_concentration": result[
                            "dirichlet_concentration"
                        ],
                        "rho2": result["rho2"],
                        "rho3": result["rho3"],
                        "n_paths": result["n_paths"],
                        "path_length": result["path_length"],
                        "overlap_fraction": result["overlap_fraction"],
                        "mu_order_1": result["mu_by_order"].get(1, np.nan),
                        "mu_order_2": result["mu_by_order"].get(2, np.nan),
                        "mu_order_3": result["mu_by_order"].get(3, np.nan),
                    }
                )
    return pd.DataFrame(rows)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-nodes", type=int, default=20)
    parser.add_argument("--n-modes", type=int, nargs="+", default=[2, 5, 10])
    parser.add_argument("--n-paths", type=int, default=25)
    parser.add_argument("--path-length", type=int, default=300)
    parser.add_argument("--conditions", nargs="+", default=["mixed"])
    parser.add_argument(
        "--orders",
        type=int,
        nargs="+",
        default=[3],
        help="maximum context order; leaf mode order=3 is the mixed VOCMN target",
    )
    parser.add_argument(
        "--target-mode",
        choices=["leaf", "raw"],
        default="leaf",
        help="leaf uses true train leaf contexts; raw is fixed-order diagnostics",
    )
    parser.add_argument(
        "--target-source",
        choices=["population", "empirical"],
        default="population",
        help="population uses true leaf probabilities; empirical uses path counts and suffix priors",
    )
    parser.add_argument(
        "--anchor-contexts",
        action=argparse.BooleanOptionalAction,
        default=True,
        help="reserve one pure mode anchor per mode among second-order leaves",
    )
    parser.add_argument("--overlaps", type=float, nargs="+", default=[0.0])
    parser.add_argument(
        "--dirichlet-concentrations",
        type=float,
        nargs="+",
        default=[0.5, 1.0, 1.5],
        help="Dirichlet c grid; the default reproduces the three c levels",
    )
    parser.add_argument("--rho2", type=float, default=0.35)
    parser.add_argument("--rho3", type=float, default=0.35)
    parser.add_argument("--max-rank", type=int, default=15)
    parser.add_argument("--n-candidates", type=int, default=5)
    parser.add_argument("--n-null", type=int, default=50)
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--seed", type=int, default=2025)
    parser.add_argument("--out-dir", default="results/variable_order")
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    os.makedirs(args.out_dir, exist_ok=True)
    results = run_grid(
        conditions=args.conditions,
        orders=args.orders,
        modes=args.n_modes,
        concentrations=args.dirichlet_concentrations,
        overlaps=args.overlaps,
        repeats=args.repeats,
        seed=args.seed,
        target_mode=args.target_mode,
        target_source=args.target_source,
        anchor_contexts=args.anchor_contexts,
        n_nodes=args.n_nodes,
        n_paths=args.n_paths,
        path_length=args.path_length,
        rho2=args.rho2,
        rho3=args.rho3,
        max_rank=args.max_rank,
        n_candidates=args.n_candidates,
        n_null=args.n_null,
    )
    main_path = os.path.join(args.out_dir, "fig2_main.png")
    plot_formal_main(results, output_path=main_path)
    metrics = results_long_table(results)
    csv_path = os.path.join(args.out_dir, "metrics.csv")
    metrics.to_csv(csv_path, index=False)
    parquet_path = os.path.join(args.out_dir, "metrics.parquet")
    try:
        metrics.to_parquet(parquet_path, index=False)
    except (ImportError, ValueError):
        parquet_path = None
    print(f"completed {len(results)} replicates")
    print(f"saved {csv_path}")
    if parquet_path:
        print(f"saved {parquet_path}")
    print(f"saved {main_path}")


if __name__ == "__main__":
    main()
